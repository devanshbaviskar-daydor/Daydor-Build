"""Finds enum values the backend actually writes or compares against.

The model has 88 enum columns and none lists its values. This scans the backend's Python (SQL
strings and test fixtures) and SQL migrations for literals tied to a model enum column, so the UI
can offer real options and labels today. It is conservative: a column with no discovered value is
listed as unlisted rather than guessed."""
from __future__ import annotations

import ast
import json
import re
from pathlib import Path

from .access import model

IGNORE_DIRS = {"__pycache__", ".git", ".venv", "node_modules"}


def _enum_columns() -> dict[str, set[str]]:
    return {t.id: {c.name for c in t.columns if c.type == "enum"} for t in model().tables
            if any(c.type == "enum" for c in t.columns)}


def _tables_in(sql: str, known: set[str]) -> set[str]:
    found = set()
    for m in re.finditer(r"\b(?:FROM|INTO|UPDATE|JOIN)\s+(?:public\.)?\"?([a-z_]+)\"?", sql, re.I):
        if m.group(1) in known:
            found.add(m.group(1))
    return found


def _literals(sql: str, enums: dict[str, set[str]], tables: set[str]):
    for table in tables:
        for col in enums.get(table, ()):
            for m in re.finditer(rf"\b{col}\s*(?:=|!=|<>)\s*'([^']+)'", sql):
                yield table, col, m.group(1)
            for m in re.finditer(rf"\b{col}\s+(?:NOT\s+)?IN\s*\(([^)]*)\)", sql, re.I):
                for lit in re.findall(r"'([^']+)'", m.group(1)):
                    yield table, col, lit
    for m in re.finditer(r"INSERT\s+INTO\s+(?:public\.)?\"?([a-z_]+)\"?\s*\(([^)]*)\)\s*VALUES\s*\((.*?)\)\s*(?:RETURNING|ON\s|;|$)",
                         sql, re.I | re.S):
        table, cols = m.group(1), [c.strip().strip('"') for c in m.group(2).split(",")]
        vals = [v.strip() for v in re.split(r",(?![^(]*\))", m.group(3))]
        if len(cols) != len(vals):
            continue
        for col, val in zip(cols, vals):
            lit = re.fullmatch(r"'([^']+)'", val)
            if lit and col in enums.get(table, ()):
                yield table, col, lit.group(1)


def _python_strings(path: Path):
    try:
        tree = ast.parse(path.read_text())
    except SyntaxError:
        return
    for node in ast.walk(tree):
        if isinstance(node, ast.Constant) and isinstance(node.value, str) and len(node.value) > 12:
            yield node.value
        if isinstance(node, ast.Call):
            fn = node.func
            name = fn.id if isinstance(fn, ast.Name) else getattr(fn, "attr", "")
            if name == "insert" and len(node.args) >= 2 and isinstance(node.args[1], ast.Constant):
                yield ("__insert__", node.args[1].value,
                       {k.arg: k.value.value for k in node.keywords
                        if k.arg and isinstance(k.value, ast.Constant) and isinstance(k.value.value, str)})


def scan(backend_root: Path) -> dict:
    enums = _enum_columns()
    known = set(enums)
    found: dict[str, dict[str, set[str]]] = {}

    def add(table, col, val, src):
        found.setdefault(f"{table}.{col}", {}).setdefault(val, set()).add(src)

    for path in sorted(backend_root.rglob("*")):
        if not path.is_file() or IGNORE_DIRS & set(path.parts):
            continue
        rel = str(path.relative_to(backend_root))
        if path.suffix == ".py" and (rel.startswith("src/") or rel.startswith("tests/")):
            for item in _python_strings(path):
                if isinstance(item, tuple):
                    _, table, kwargs = item
                    for col, val in kwargs.items():
                        if col in enums.get(table, ()):
                            add(table, col, val, rel)
                else:
                    for table, col, val in _literals(item, enums, _tables_in(item, known)):
                        add(table, col, val, rel)
        elif path.suffix == ".sql" and "migrations/sql" in rel:
            for stmt in path.read_text().split(";"):
                for table, col, val in _literals(stmt, enums, _tables_in(stmt, known)):
                    add(table, col, val, rel)
    return {k: {v: sorted(s) for v, s in sorted(vals.items())} for k, vals in sorted(found.items())}


def build(backend_root: Path, overrides: dict) -> dict:
    scanned = scan(backend_root)
    all_cols = sorted(f"{t}.{c}" for t, cs in _enum_columns().items() for c in cs)
    out = {}
    for key in all_cols:
        values = dict(scanned.get(key, {}))
        for v in overrides.get(key, []):
            values.setdefault(v, ["overrides.json"])
        if values:
            out[key] = {"values": sorted(values), "sources": {v: s for v, s in sorted(values.items())}}
    return {
        "note": "Provisional. Generated by scripts/gen_enums.py from the backend's code. Delete when the model carries value lists.",
        "enum_column_count": len(all_cols),
        "enums": out,
        "unlisted": [k for k in all_cols if k not in out],
    }


def write(backend_root: Path, out_path: Path, overrides_path: Path) -> dict:
    result = build(backend_root, json.loads(overrides_path.read_text()))
    out_path.write_text(json.dumps(result, indent=1, sort_keys=False) + "\n")
    return result
