"""Generates skeleton workflow definitions from the artifact's six flows.

Each flow becomes a linear machine: start -> one state per step -> done, advanced by "advance".
Entering a step enqueues that step's worker on its domain queue. A step's gate guards the
transition into it. Gates whose need depends on the data (out-of-band offer, adverse finding,
active legal hold...) are conditional on a context flag "requires_<gate>"; the agent that
evaluates the condition sets it. Hand-written definitions can replace these per flow.
"""
from __future__ import annotations

import json

from daydor.model import load_model

UNCONDITIONAL_GATES = {"g_pay_disburse", "g_finalpay", "g_it_deprov", "g_close", "dpdp_consent",
                       "threshold_crossing", "wage_structure_change"}
DOMAIN_QUEUE = {"ro": "platform", "priv": "privacy", "ref": "platform"}


def _slug(s: str) -> str:
    return "".join(ch if ch.isalnum() else "_" for ch in s.lower()).strip("_")


def flow_definition(flow: dict) -> dict:
    model = load_model()
    states: dict[str, dict] = {}
    names = ["start"] + [f"s{i + 1:02d}_{_slug(step[0])}" for i, step in enumerate(flow["steps"])] + ["done"]
    for i, name in enumerate(names):
        spec: dict = {"terminal": name == "done"}
        if 0 < i < len(names) - 1:
            table, _op, worker = flow["steps"][i - 1][:3]
            domain = model.table(table).domain
            spec["enter_jobs"] = [{"queue": DOMAIN_QUEUE.get(domain, domain), "kind": _slug(worker)}]
        if i < len(names) - 1:
            nxt = names[i + 1]
            transition: dict = {"to": nxt}
            if 0 <= i < len(flow["steps"]):
                step = flow["steps"][i]
                gate = step[4] if len(step) > 4 else ""
                if gate:
                    transition["gate"] = gate
                    if gate not in UNCONDITIONAL_GATES:
                        transition["gate_if"] = f"requires_{gate}"
            spec["on"] = {"advance": transition}
        states[name] = spec
    return {"initial": "start", "states": states, "description": flow["sum"], "title": flow["name"]}


def seed_sql() -> str:
    lines = ["-- GENERATED by daydor.workflow.definitions.seed_sql(). Do not edit by hand.",
             "SET ROLE daydor_schema_owner;"]
    for flow in load_model().flows:
        body = json.dumps(flow_definition(flow), sort_keys=True).replace("'", "''")
        lines.append(f"INSERT INTO app.workflow_definition (name, version, definition, source) "
                     f"VALUES ('{flow['id']}', 1, '{body}'::jsonb, 'model-flow');")
    lines += ["RESET ROLE;", ""]
    return "\n".join(lines)


if __name__ == "__main__":  # pragma: no cover
    from pathlib import Path
    Path("migrations/sql/0010_workflow_seed.sql").write_text(seed_sql())
    print("wrote migrations/sql/0010_workflow_seed.sql")
