"""Hire flow steps 1-2 (position check, requisition drafting).

These run synchronously, before any workflow instance exists -- not as queued workflow steps.
`id` columns never carry an INSERT grant for any role (every table's `id` is DB-generated by
convention; see `daydor.model.ddl.SYSTEM_MANAGED`), so a workflow instance's subject_id, which is
set once at `WorkflowEngine.start()` and never changes, cannot be a `job_requisition.id` that is
allocated *after* the instance starts. The requisition has to exist first. See
`daydor.hire.workflow.start_hire`, which calls `open_requisition` and then starts the instance
against the id it returns, firing "advance" through the now-synchronous s01/s02 states that
record this in the transition log for audit even though the work already happened.

`position` is admin-entered directly by tenant_hr/tenant_founder (see docs/sprint-plan.md's
"Reference & admin-owned data" note) -- this module only reads it to validate.
"""
from __future__ import annotations

from datetime import date
from uuid import UUID

from sqlalchemy import Connection, text


class NoVacantPosition(RuntimeError):
    pass


def confirm_budgeted_seat(conn: Connection, position_id: UUID) -> None:
    """Raise unless position_id is an open, vacant, budgeted seat."""
    row = conn.execute(
        text("SELECT status, budgeted_fte, current_employee_id FROM position WHERE id = :p"),
        {"p": position_id}).one_or_none()
    if row is None:
        raise NoVacantPosition(f"position {position_id} not found")
    if row.status != "open" or row.current_employee_id is not None or row.budgeted_fte <= 0:
        raise NoVacantPosition(f"position {position_id} is not an open, vacant, budgeted seat")


def open_requisition(conn: Connection, *, position_id: UUID, hiring_manager_id: UUID,
                     target_start_date: date) -> UUID:
    """Confirm the seat, then draft a requisition against it. Idempotent: a position has at most
    one live (not rejected/cancelled) requisition at a time; calling this again for the same
    position returns the existing one instead of drafting a duplicate."""
    confirm_budgeted_seat(conn, position_id)
    existing = conn.execute(
        text("SELECT id FROM job_requisition WHERE position_id = :p "
             "AND status NOT IN ('rejected', 'cancelled')"), {"p": position_id}).scalar_one_or_none()
    if existing is not None:
        return existing
    return conn.execute(
        text("INSERT INTO job_requisition (position_id, hiring_manager_id, status, target_start_date) "
             "VALUES (:p, :h, 'draft', :d) RETURNING id"),
        {"p": position_id, "h": hiring_manager_id, "d": target_start_date},
    ).scalar_one()
