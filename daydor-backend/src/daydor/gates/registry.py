"""Gate registry: the model's 20 hard gates, platform soft gates, and DB-enforced write guards.

seed_sql() renders migrations/sql/0007_gate_seed.sql. Soft gates live here (not in the artifact)
because they are a platform decision; each one names the hard gate it escalates to.
"""
from __future__ import annotations

from dataclasses import dataclass

from daydor.model import load_model
from daydor.model.loader import ROLE_DB


@dataclass(frozen=True)
class HardGateDef:
    """A hard gate the backend needs that the artifact's model doesn't define yet. Each one here
    is a documented gap (see docs/model-findings.md) to push back into the artifact once the
    shape has proven out; until then this is the single place new ones get added."""
    gate_id: str
    label: str
    approver_roles: tuple[str, ...]      # database role names (ROLE_DB values), not model letters
    tables: tuple[str, ...]


@dataclass(frozen=True)
class SoftGateDef:
    gate_id: str
    label: str
    escalate_to: str
    tables: tuple[str, ...]
    max_input_class: str          # highest column class a model may see: S, C0, C1 or C2
    auto_pass_threshold: float
    mode: str = "shadow"          # every soft gate starts in shadow mode


# Finding 11 (docs/model-findings.md): no gate in the model covers requisition budget sign-off,
# though the hire flow's "approval_request W requisition-approval-router" step needs one.
#
# Finding 9: managers have read-only access to approval_request, but timecard-approval-router
# (and, on the expense side, expense-approval-router) send approvals to managers, and no gate in
# the model names the manager as an approver. g_timecard is what Sprint 6
# (docs/sprint-plan.md) needs; g_expense is added at the same time since it's the same gap on
# the same table_acl shape, even though no expense domain service exists yet to raise it.
PLATFORM_HARD_GATES = (
    HardGateDef("g_requisition_budget", "Requisition budget sign-off",
               approver_roles=("tenant_founder",), tables=("job_requisition",)),
    HardGateDef("g_timecard", "Timecard approval",
               approver_roles=("tenant_manager",), tables=("timecard",)),
    HardGateDef("g_expense", "Expense report approval",
               approver_roles=("tenant_manager",), tables=("expense",)),
)

SOFT_GATES = (
    SoftGateDef("sg_payroll_anomaly_precheck",
                "Pre-check: does this payroll run look normal against history?",
                escalate_to="g_pay_anomaly", tables=("payroll_run",), max_input_class="C2",
                auto_pass_threshold=0.90),
    SoftGateDef("sg_access_request_precheck",
                "Pre-check: is this access request consistent with the person's role?",
                escalate_to="g_it_offtemplate", tables=("app_access_grant",), max_input_class="C1",
                auto_pass_threshold=0.95),
)

# Unconditional guards: setting the column needs an approved gate for that row.
# Conditional gates (out-of-band offer, AP above materiality, 409A staleness) are decided in
# the application, because the condition depends on data the trigger should not own.
GUARDS = (
    ("payroll_run", "disbursed_at", ("g_pay_disburse",)),
    # g_pay_disburse, not g_finalpay: the model's own g_pay_disburse.tables names
    # final_settlement alongside payroll_run/contractor_invoice (finding 20). g_finalpay gates the
    # *calculated amounts* as a workflow-level checkpoint (daydor.exit.workflow), not this column.
    ("final_settlement", "disbursed_at", ("g_pay_disburse",)),
    ("contractor_invoice", "paid_at", ("g_pay_disburse",)),
    ("gl_journal_entry", "posted_at", ("g_close",)),
    ("identity_account", "deprovisioned_at", ("g_it_deprov",)),
    ("cobra_event", "notice_sent_at", ("g_cobra",)),
    ("er_case", "outcome", ("g_er_adjud",)),
    # Finding 23 follow-up (ADR-006): the DB refuses these without an approved gate, even though no service writes them yet.
    ("expense", "reimbursed_at", ("g_expense",)),
    ("leave_request", "fmla_designation", ("g_fmla",)),
)


def _lit(s: str | None) -> str:
    return "NULL" if s is None else "'" + s.replace("'", "''") + "'"


def _arr(items) -> str:
    return "ARRAY[" + ", ".join(_lit(i) for i in items) + "]::text[]" if items else "'{}'::text[]"


def seed_sql() -> str:
    model = load_model()
    tables = {t.id for t in model.tables}
    lines = ["-- GENERATED by daydor.gates.registry.seed_sql(). Do not edit by hand.",
             "SET ROLE daydor_schema_owner;", ""]
    for g in model.gates:
        roles = [ROLE_DB[a] for a in g["ap"]]
        lines.append(
            "INSERT INTO app.gate_definition (gate_id, label, kind, approver_roles, tables, source) "
            f"VALUES ({_lit(g['id'])}, {_lit(g['label'])}, 'hard', {_arr(roles)}, {_arr(g['tables'])}, "
            f"{_lit(g['src'])});")
    for g in PLATFORM_HARD_GATES:
        assert set(g.tables) <= tables, g
        lines.append(
            "INSERT INTO app.gate_definition (gate_id, label, kind, approver_roles, tables, source) "
            f"VALUES ({_lit(g.gate_id)}, {_lit(g.label)}, 'hard', {_arr(g.approver_roles)}, "
            f"{_arr(g.tables)}, 'platform');")
    for s in SOFT_GATES:
        assert s.max_input_class in ("S", "C0", "C1", "C2"), s
        assert set(s.tables) <= tables, s
        lines.append(
            "INSERT INTO app.gate_definition (gate_id, label, kind, tables, source, escalate_to, mode, "
            "auto_pass_threshold, max_input_class, reversible) "
            f"VALUES ({_lit(s.gate_id)}, {_lit(s.label)}, 'soft', {_arr(s.tables)}, 'platform', "
            f"{_lit(s.escalate_to)}, {_lit(s.mode)}, {s.auto_pass_threshold}, {_lit(s.max_input_class)}, true);")
    lines.append("")
    for table, column, gates in GUARDS:
        assert table in tables, table
        model.table(table).column(column)
        model.table(table).column("approval_request_id")
        lines.append(f"INSERT INTO app.gate_guard VALUES ({_lit(table)}, {_lit(column)}, {_arr(gates)});")
    lines.append("")
    for table in sorted({g[0] for g in GUARDS}):
        lines.append(f"CREATE TRIGGER {table}_gate_guard BEFORE INSERT OR UPDATE ON public.{table} "
                     f"FOR EACH ROW EXECUTE FUNCTION app.enforce_gate_guard();")
    lines += ["", "RESET ROLE;", ""]
    return "\n".join(lines)


if __name__ == "__main__":  # pragma: no cover
    from pathlib import Path
    Path("migrations/sql/0007_gate_seed.sql").write_text(seed_sql())
    print("wrote migrations/sql/0007_gate_seed.sql")
